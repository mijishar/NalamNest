def _matches(text: str, phrases: list[str]) -> list[str]:
    low = text.lower()
    return [p for p in phrases if p.lower() in low]


def check(text: str) -> tuple[str | None, list[str]]:
    """Return (trigger_type, matched_phrases) or (None, []) if safe.

    trigger_type is 'emergency' or 'medical'.
    """
    emergency_hits = _matches(text, EMERGENCY_PHRASES)
    if emergency_hits:
        return "emergency", emergency_hits
    medical_hits = _matches(text, MEDICAL_SAFETY_PHRASES)
    if medical_hits:
        return "medical", medical_hits
    return None, []


# ---------------------------------------------------------------------------
# Strands hook — cancels all graph nodes before they run
# ---------------------------------------------------------------------------

class SafetyGate(HookProvider):
    """Cancels every graph node when the user message contains a safety phrase.

    gate.trigger_type: 'emergency' | 'medical' | None
    gate.tripped: list of matched phrases
    """

    def __init__(self) -> None:
        self.trigger_type: str | None = None
        self.tripped: list[str] = []

    def register_hooks(self, registry: HookRegistry, **_) -> None:
        registry.add_callback(BeforeNodeCallEvent, self._before)

    def _before(self, event: BeforeNodeCallEvent) -> None:
        text = str(event.invocation_state.get("user_text", ""))
        trigger, hits = check(text)
        if trigger:
            self.trigger_type = trigger
            self.tripped = hits
            event.cancel_node = f"safety-{trigger}: " + ", ".join(hits)
